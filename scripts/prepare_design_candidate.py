#!/usr/bin/env python3
"""Prepare one ranked fadrozole analog for the relaxed exchange-cycle screen.

The shared heavy-atom maximum common substructure is constrained to the seed
pose separately in each enzyme.  New substituent atoms are generated by RDKit.
The output remains provisional and must pass geometry/bond audits after UMA.
"""

import argparse
import copy
import json
import math
import os
from pathlib import Path
import sys

import numpy as np
from rdkit import Chem
from rdkit.Chem import AllChem, rdFMCS
from rdkit.Geometry import Point3D


ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(os.environ.get('ISOFORM_SOURCE_ROOT', ROOT / 'research/source-preparation'))
sys.path.insert(0, str(SOURCE))
import prepare_whole


def seed_molecule():
    atoms, _ = prepare_whole.read_source(SOURCE / "inputs/6M7X.pdb")
    rows = prepare_whole.ccd_table(SOURCE / "inputs/JD7.cif", "_chem_comp_atom")
    bond_rows = prepare_whole.ccd_table(SOURCE / "inputs/JD7.cif", "_chem_comp_bond")
    observed = {entry["name"]: entry for entry in atoms if entry["res"] == "JD7"}
    heavy = [row for row in rows if row["type_symbol"] != "H"]
    molecule = Chem.RWMol()
    names = {}
    for row in heavy:
        atom = Chem.Atom(row["type_symbol"].title())
        atom.SetFormalCharge(int(row["charge"]))
        atom.SetProp("seed_name", row["atom_id"])
        names[row["atom_id"]] = molecule.AddAtom(atom)
    orders = {
        "SING": Chem.BondType.SINGLE,
        "DOUB": Chem.BondType.DOUBLE,
        "TRIP": Chem.BondType.TRIPLE,
    }
    for row in bond_rows:
        left, right = row["atom_id_1"], row["atom_id_2"]
        if left in names and right in names:
            molecule.AddBond(names[left], names[right], orders[row["value_order"]])
    molecule = molecule.GetMol()
    Chem.SanitizeMol(molecule)
    conformer = Chem.Conformer(molecule.GetNumAtoms())
    conformer.Set3D(True)
    for name, index in names.items():
        conformer.SetAtomPosition(index, observed[name]["xyz"])
    molecule.AddConformer(conformer)
    Chem.AssignAtomChiralTagsFromStructure(molecule, replaceExistingTags=True)
    Chem.AssignStereochemistry(molecule, cleanIt=True, force=True)
    return molecule, {index: name for name, index in names.items()}


def find_mapping(seed, candidate):
    exact_matches = candidate.GetSubstructMatches(
        seed, uniquify=False, useChirality=True, maxMatches=16
    )
    if exact_matches:
        match = exact_matches[0]
        return {candidate_index: seed_index
                for seed_index, candidate_index in enumerate(match)}, seed.GetNumAtoms()
    result = rdFMCS.FindMCS(
        [seed, candidate],
        atomCompare=rdFMCS.AtomCompare.CompareElements,
        bondCompare=rdFMCS.BondCompare.CompareOrder,
        ringMatchesRingOnly=True,
        completeRingsOnly=True,
        matchChiralTag=True,
        timeout=20,
    )
    if result.canceled or result.numAtoms < 14:
        raise ValueError(f"Insufficient seed common substructure: {result.numAtoms} heavy atoms")
    query = Chem.MolFromSmarts(result.smartsString)
    seed_matches = seed.GetSubstructMatches(
        query, uniquify=False, useChirality=True, maxMatches=64
    )
    candidate_matches = candidate.GetSubstructMatches(
        query, uniquify=False, useChirality=True, maxMatches=64
    )
    if not seed_matches or not candidate_matches:
        raise ValueError("Could not map candidate to the stereospecific seed")
    # Favor the mapping that retains the named heme-binding N06 and chiral C03.
    required = {
        atom.GetIdx() for atom in seed.GetAtoms()
        if atom.HasProp("seed_name") and atom.GetProp("seed_name") in {"N06", "C03"}
    }
    choices = []
    for seed_match in seed_matches:
        retained = len(required & set(seed_match))
        for candidate_match in candidate_matches:
            choices.append((retained, seed_match, candidate_match))
    retained, seed_match, candidate_match = max(choices, key=lambda row: row[0])
    if retained != len(required):
        raise ValueError("Candidate does not retain the chiral center and heme-binding nitrogen")
    return dict(zip(candidate_match, seed_match)), result.numAtoms


def atom_ids(candidate, mapping, seed_names):
    ids = {}
    used = set()
    for candidate_index, seed_index in mapping.items():
        name = "ligand_" + seed_names[seed_index]
        ids[candidate_index] = name
        used.add(name)
    counters = {}
    for atom in candidate.GetAtoms():
        index = atom.GetIdx()
        if index in ids:
            continue
        if atom.GetSymbol() == "H":
            parent = atom.GetNeighbors()[0].GetIdx()
            parent_id = ids.get(parent, f"ligand_{candidate.GetAtomWithIdx(parent).GetSymbol()}{parent}")
            counters[parent_id] = counters.get(parent_id, 0) + 1
            name = f"{parent_id}_H{counters[parent_id]}"
        else:
            name = f"ligand_new_{atom.GetSymbol()}{index:02d}"
        while name in used:
            name += "x"
        ids[index] = name
        used.add(name)
    return ids


def embed_to_pose(candidate_template, mapping, seed_names, ids, target_positions, seed, attempts=6):
    coord_map = {}
    atom_map = []
    for candidate_index, seed_index in mapping.items():
        seed_id = "ligand_" + seed_names[seed_index]
        if seed_id not in target_positions:
            continue
        point = target_positions[seed_id][1]
        coord_map[candidate_index] = Point3D(*map(float, point))
        atom_map.append((candidate_index, seed_index))
    if len(coord_map) < 14:
        raise ValueError("Too few mapped pose coordinates")

    scaffold_heavy = np.asarray([
        position for atom_id, (element, position) in target_positions.items()
        if not atom_id.startswith("ligand_") and element != "H" and atom_id != "heme_FE"
    ])
    best = None
    for attempt in range(attempts):
        molecule = Chem.Mol(candidate_template)
        status = AllChem.EmbedMolecule(
            molecule,
            coordMap=coord_map,
            randomSeed=20260919 + attempt,
            useRandomCoords=True,
            enforceChirality=True,
            clearConfs=True,
        )
        if status != 0:
            continue
        conformer = molecule.GetConformer()
        candidate_heavy = np.asarray([
            list(conformer.GetAtomPosition(atom.GetIdx()))
            for atom in molecule.GetAtoms() if atom.GetSymbol() != "H"
        ])
        minimum = float(np.min(np.linalg.norm(
            candidate_heavy[:, None, :] - scaffold_heavy[None, :, :], axis=2
        )))
        mapped_rms = math.sqrt(sum(
            np.sum((np.asarray(conformer.GetAtomPosition(index)) - np.asarray([
                coord_map[index].x, coord_map[index].y, coord_map[index].z
            ])) ** 2)
            for index in coord_map
        ) / len(coord_map))
        score = minimum - 2.0 * mapped_rms
        if best is None or score > best[0]:
            best = (score, molecule, minimum, mapped_rms)
    if best is None:
        molecule = Chem.Mol(candidate_template)
        status = AllChem.EmbedMolecule(
            molecule, randomSeed=20260919, enforceChirality=True, clearConfs=True
        )
        if status != 0:
            raise ValueError("RDKit could not embed the candidate in the seed pose")
        conformer = molecule.GetConformer()
        indices = sorted(coord_map)
        source = np.asarray([
            list(conformer.GetAtomPosition(index)) for index in indices
        ])
        target = np.asarray([
            [coord_map[index].x, coord_map[index].y, coord_map[index].z]
            for index in indices
        ])
        source_center, target_center = source.mean(0), target.mean(0)
        left, _, right = np.linalg.svd(
            (source - source_center).T @ (target - target_center)
        )
        rotation = left @ right
        if np.linalg.det(rotation) < 0:
            left[:, -1] *= -1
            rotation = left @ right
        for atom in molecule.GetAtoms():
            index = atom.GetIdx()
            point = np.asarray(conformer.GetAtomPosition(index))
            aligned = (point - source_center) @ rotation + target_center
            conformer.SetAtomPosition(index, Point3D(*map(float, aligned)))
        deltas = {
            index: np.asarray([coord_map[index].x, coord_map[index].y, coord_map[index].z])
            - np.asarray(conformer.GetAtomPosition(index))
            for index in indices
        }
        unmapped = set(range(molecule.GetNumAtoms())) - set(indices)
        while unmapped:
            start = next(iter(unmapped))
            component = {start}
            frontier = [start]
            while frontier:
                current = frontier.pop()
                for neighbor in molecule.GetAtomWithIdx(current).GetNeighbors():
                    index = neighbor.GetIdx()
                    if index in unmapped and index not in component:
                        component.add(index)
                        frontier.append(index)
            boundaries = {
                neighbor.GetIdx()
                for index in component
                for neighbor in molecule.GetAtomWithIdx(index).GetNeighbors()
                if neighbor.GetIdx() in deltas
            }
            shift = (np.mean([deltas[index] for index in boundaries], axis=0)
                     if boundaries else np.zeros(3))
            for index in component:
                point = np.asarray(conformer.GetAtomPosition(index)) + shift
                conformer.SetAtomPosition(index, Point3D(*map(float, point)))
            unmapped -= component
        for index in indices:
            conformer.SetAtomPosition(index, coord_map[index])
        candidate_heavy = np.asarray([
            list(conformer.GetAtomPosition(atom.GetIdx()))
            for atom in molecule.GetAtoms() if atom.GetSymbol() != "H"
        ])
        minimum = float(np.min(np.linalg.norm(
            candidate_heavy[:, None, :] - scaffold_heavy[None, :, :], axis=2
        )))
        best = (minimum, molecule, minimum, 0.0)
    _, molecule, minimum, mapped_rms = best
    conformer = molecule.GetConformer()
    atoms = [
        {
            "id": ids[index],
            "element": atom.GetSymbol(),
            "position": list(map(float, conformer.GetAtomPosition(index))),
        }
        for index, atom in enumerate(molecule.GetAtoms())
    ]
    return molecule, atoms, minimum, mapped_rms


def free_pose(candidate_template, ids):
    molecule = Chem.Mol(candidate_template)
    status = AllChem.EmbedMolecule(molecule, randomSeed=20260919, enforceChirality=True)
    if status != 0:
        raise ValueError("RDKit could not embed the free candidate")
    try:
        AllChem.MMFFOptimizeMolecule(molecule, maxIters=500)
    except ValueError:
        AllChem.UFFOptimizeMolecule(molecule, maxIters=500)
    conformer = molecule.GetConformer()
    return [
        {
            "id": ids[index],
            "element": atom.GetSymbol(),
            "position": list(map(float, conformer.GetAtomPosition(index))),
        }
        for index, atom in enumerate(molecule.GetAtoms())
    ]


def covalent_bounds(molecule, ids):
    return [
        {"ids": [ids[bond.GetBeginAtomIdx()], ids[bond.GetEndAtomIdx()]],
         "min_A": 0.7, "max_A": 1.95}
        for bond in molecule.GetBonds()
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("campaign", type=Path)
    parser.add_argument("candidate_id")
    parser.add_argument("--seed-manifest", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    campaign = json.loads(args.campaign.read_text())
    candidate_record = next(
        (row for row in campaign["candidates"] if row["id"] == args.candidate_id), None
    )
    if candidate_record is None:
        raise ValueError(f"Unknown candidate: {args.candidate_id}")
    candidate = Chem.AddHs(Chem.MolFromSmiles(candidate_record["canonical_smiles"]))
    if candidate is None:
        raise ValueError("Invalid candidate SMILES")
    seed, seed_names = seed_molecule()
    candidate_heavy = Chem.RemoveHs(candidate)
    mapping, common_atoms = find_mapping(seed, candidate_heavy)
    ids = atom_ids(candidate, mapping, seed_names)
    donor_index = next(index for index, seed_index in mapping.items() if seed_names[seed_index] == "N06")
    donor_id = ids[donor_index]
    center_index = next(index for index, seed_index in mapping.items() if seed_names[seed_index] == "C03")

    manifest = json.loads(args.seed_manifest.read_text())
    manifest["ligand"] = candidate_record["name"]
    manifest["preparation_protocol"] += (
        f"; design analog {args.candidate_id} from RDKit constrained common-substructure embedding"
    )
    audit = {
        "candidate_id": args.candidate_id,
        "canonical_smiles": candidate_record["canonical_smiles"],
        "common_heavy_atoms": common_atoms,
        "formal_charge": int(Chem.GetFormalCharge(candidate)),
        "poses": {},
    }
    free_atoms = free_pose(candidate, ids)
    bounds = covalent_bounds(candidate, ids)
    chiral_neighbors = [
        neighbor.GetIdx() for neighbor in candidate.GetAtomWithIdx(center_index).GetNeighbors()
        if neighbor.GetSymbol() != "H"
    ]
    if len(chiral_neighbors) != 3:
        raise ValueError("Expected one three-connected retained stereocenter")
    free_coordinates = {atom["id"]: np.asarray(atom["position"]) for atom in free_atoms}
    free_center = free_coordinates[ids[center_index]]
    neighbor_ids = [ids[index] for index in chiral_neighbors]
    free_volume = float(np.linalg.det(np.asarray([
        free_coordinates[name] - free_center for name in neighbor_ids
    ])))
    free_reference = copy.deepcopy(manifest["enzymes"]["CYP11B1"]["free_ligand"])
    free_reference["atoms"] = copy.deepcopy(free_atoms)
    free_reference["state"] = {
        "charge": int(Chem.GetFormalCharge(candidate)),
        "multiplicity": 1,
        "convention": "Neutral closed-shell design analog; explicit protonation review required.",
    }
    free_reference["fixed_ids"] = []
    free_reference["preparation"] = manifest["preparation_protocol"]
    free_reference["covalent_bounds"] = bounds
    free_reference["chirality_checks"] = [{
        "center": ids[center_index],
        "neighbors": neighbor_ids,
        "reference_volume_A3": free_volume,
    }]
    free_reference["provenance"] = {
        "candidate_id": args.candidate_id,
        "canonical_smiles": candidate_record["canonical_smiles"],
        "pose_kind": "RDKit_ETKDG_free_ligand",
    }

    for enzyme, parts in manifest["enzymes"].items():
        seed_cluster = parts["cluster_ligand"]
        target_positions = {
            atom["id"]: (atom["element"], atom["position"]) for atom in seed_cluster["atoms"]
        }
        pose_lookup = {key: value[1] for key, value in target_positions.items()}
        embedded, ligand_atoms, minimum, mapped_rms = embed_to_pose(
            candidate, mapping, seed_names, ids, target_positions, seed
        )
        scaffold = [
            copy.deepcopy(atom) for atom in seed_cluster["atoms"]
            if atom["id"] in seed_cluster["scaffold_ids"]
        ]
        cluster = copy.deepcopy(seed_cluster)
        cluster["atoms"] = scaffold + ligand_atoms
        cluster["coordination"] = [
            {**bound, "ids": [bound["ids"][0], donor_id]}
            if "ligand_N06" in bound["ids"] else bound
            for bound in cluster["coordination"]
        ]
        cluster["covalent_bounds"] = bounds
        coordinates = {atom["id"]: np.asarray(atom["position"]) for atom in ligand_atoms}
        center = coordinates[ids[center_index]]
        volume = float(np.linalg.det(np.asarray([coordinates[name] - center for name in neighbor_ids])))
        cluster["chirality_checks"] = [{
            "center": ids[center_index],
            "neighbors": neighbor_ids,
            "reference_volume_A3": volume,
        }]
        cluster["state"]["charge"] += int(Chem.GetFormalCharge(candidate))
        cluster["preparation"] = manifest["preparation_protocol"]
        cluster.setdefault("provenance", {}).update({
            "candidate_id": args.candidate_id,
            "canonical_smiles": candidate_record["canonical_smiles"],
            "pose_kind": "RDKit_constrained_seed_analog_pose",
            "common_heavy_atoms": common_atoms,
            "mapped_pose_RMSD_A": mapped_rms,
        })
        parts["cluster_ligand"] = cluster
        parts["free_ligand"] = copy.deepcopy(free_reference)
        audit["poses"][enzyme] = {
            "mapped_pose_RMSD_A": mapped_rms,
            "minimum_ligand_scaffold_heavy_distance_A": minimum,
            "atoms": len(ligand_atoms),
            "coordination_donor": donor_id,
        }

    sys.path.insert(0, str(ROOT))
    from cyp_pipeline.exchange import structure_valid, validate_manifest
    for enzyme, parts in manifest["enzymes"].items():
        if not structure_valid(parts["cluster_ligand"]["atoms"], parts["cluster_ligand"]):
            raise ValueError(f"{enzyme}: prepared ligand pose failed covalent/chirality guards")
        if not structure_valid(parts["free_ligand"]["atoms"], parts["free_ligand"]):
            raise ValueError(f"{enzyme}: prepared free ligand failed covalent/chirality guards")
    validate_manifest(manifest)
    args.out.mkdir(parents=True, exist_ok=False)
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (args.out / "preparation_audit.json").write_text(json.dumps(audit, indent=2) + "\n")
    print(json.dumps(audit, indent=2))


if __name__ == "__main__":
    main()
